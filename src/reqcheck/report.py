"""Console, Markdown and HTML reports."""

from __future__ import annotations

import html
from collections import Counter
from dataclasses import dataclass
from datetime import datetime, timezone

from .model import SEVERITIES, Finding, Project
from .rules import ears_pattern
from .trace import TraceResult


@dataclass
class CheckResult:
    project: Project
    quality: list[Finding]
    trace: TraceResult

    @property
    def findings(self) -> list[Finding]:
        return self.quality + self.trace.findings

    def count(self, severity: str) -> int:
        return sum(1 for f in self.findings if f.severity == severity)


def _sorted(findings: list[Finding]) -> list[Finding]:
    order = {s: i for i, s in enumerate(SEVERITIES)}
    return sorted(findings, key=lambda f: (order.get(f.severity, 9), f.item_id, f.rule))


# Console ------------------------------------------------------------------------
def to_console(result: CheckResult, show_info: bool = False) -> str:
    p, c = result.project, result.trace.coverage
    lines = [
        f"reqcheck: {p.name}",
        f"  {len(p.of_type('stakeholder'))} stakeholder needs, {len(p.of_type('system'))} system requirements, "
        f"{len(p.of_type('component'))} component requirements, {len(p.tests)} tests",
        "",
    ]
    for f in _sorted(result.findings):
        if f.severity == "info" and not show_info:
            continue
        lines.append(f"  {f.severity.upper():8} {f.item_id:12} {f.rule:16} {f.message}")
    lines += [
        "",
        f"  Errors: {result.count('error')}   Warnings: {result.count('warning')}   Info: {result.count('info')}",
        f"  Needs with system requirements: {c.needs_with_requirements:.1f} %",
        f"  Requirements with a parent:     {c.requirements_with_parent:.1f} %",
        f"  Requirements verified by tests: {c.requirements_verified:.1f} %",
    ]
    return "\n".join(lines)


# Markdown -----------------------------------------------------------------------
def _md(text: str) -> str:
    return text.replace("|", "\\|")


def to_markdown(result: CheckResult) -> str:
    p, c = result.project, result.trace.coverage
    out = [
        f"# Requirements check: {p.name}",
        "",
        f"Generated by reqcheck on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC.",
        "",
        "## Summary",
        "",
        "| Measure | Value |",
        "|---|---|",
        f"| Stakeholder needs | {len(p.of_type('stakeholder'))} |",
        f"| System requirements | {len(p.of_type('system'))} |",
        f"| Component requirements | {len(p.of_type('component'))} |",
        f"| Test cases | {len(p.tests)} |",
        f"| Errors / warnings / info | {result.count('error')} / {result.count('warning')} / {result.count('info')} |",
        f"| Needs with system requirements | {c.needs_with_requirements:.1f} % |",
        f"| Requirements with a parent | {c.requirements_with_parent:.1f} % |",
        f"| Requirements verified by tests | {c.requirements_verified:.1f} % |",
        "",
        "## Findings",
        "",
    ]
    findings = _sorted(result.findings)
    if findings:
        out += ["| Severity | ID | Rule | Message |", "|---|---|---|---|"]
        out += [f"| {f.severity} | {f.item_id} | {f.rule} | {_md(f.message)} |" for f in findings]
    else:
        out.append("No findings.")
    out += [
        "",
        "## Traceability matrix",
        "",
        "| ID | Type | EARS pattern | Derived from | Derived requirements | Verified by |",
        "|---|---|---|---|---|---|",
    ]
    for row in result.trace.rows:
        pattern = ears_pattern(row.item.text) if row.item.type != "stakeholder" else ""
        out.append(
            f"| {row.item.id} | {row.item.type} | {pattern or '-'} | {', '.join(row.parents) or '-'} | "
            f"{', '.join(row.children) or '-'} | {', '.join(row.tests) or '-'} |"
        )
    return "\n".join(out) + "\n"


