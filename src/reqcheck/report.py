def to_html(result: CheckResult) -> str:
    e = html.escape
    p, c = result.project, result.trace.coverage
    index = p.by_id()

    def card(value, label, percent=None):
        bar = f'<div class="bar"><span style="width:{percent}%"></span></div>' if percent is not None else ""
        return f'<div class="card"><div class="v">{value}</div><div class="k">{e(label)}</div>{bar}</div>'

    cards = "".join([
        card(len(p.of_type("stakeholder")), "stakeholder needs"),
        card(len(p.of_type("system")) + len(p.of_type("component")), "system and component requirements"),
        card(len(p.tests), "test cases"),
        card(f'<span class="error">{result.count("error")}</span>', "errors"),
        card(f'<span class="warning">{result.count("warning")}</span>', "warnings"),
        card(f"{c.needs_with_requirements:.0f} %", "needs with system requirements", c.needs_with_requirements),
        card(f"{c.requirements_with_parent:.0f} %", "requirements with a parent", c.requirements_with_parent),
        card(f"{c.requirements_verified:.0f} %", "requirements verified", c.requirements_verified),
    ])

    finding_rows = []
    for f in _sorted(result.findings):
        text = index[f.item_id].text if f.item_id in index else ""
        finding_rows.append(
            f'<tr data-sev="{f.severity}"><td class="sev {f.severity}">{f.severity}</td><td>{e(f.item_id)}</td>'
            f"<td><code>{e(f.rule)}</code></td><td>{e(f.message)}<div class='text'>{e(text)}</div></td></tr>"
        )
    findings_html = "".join(finding_rows) or '<tr><td colspan="4">No findings.</td></tr>'

    def links(ids, needed):
        if ids:
            return e(", ".join(ids))
        return '<span class="missing">missing</span>' if needed else "-"

    trace_rows = []
    for row in result.trace.rows:
        t = row.item.type
        pattern = ears_pattern(row.item.text) if t != "stakeholder" else ""
        trace_rows.append(
            f"<tr><td><b>{e(row.item.id)}</b></td><td>{t}</td><td class='text'>{e(row.item.text)}</td>"
            f"<td>{e(pattern) or '-'}</td>"
            f"<td>{links(row.parents, t in ('system', 'component'))}</td>"
            f"<td>{links(row.children, t == 'stakeholder')}</td>"
            f"<td>{links(row.tests, t in ('system', 'component'))}</td></tr>"
        )

    tests_rows = "".join(
        f"<tr><td><b>{e(t.id)}</b></td><td>{e(t.method or '-')}</td><td class='text'>{e(t.text)}</td>"
        f"<td>{e(', '.join(sorted({r.item.id for r in result.trace.rows if t.id in r.tests}))) or '-'}</td></tr>"
        for t in p.tests
    ) or '<tr><td colspan="4">No test cases.</td></tr>'

    return f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Requirements check: {e(p.name)}</title>
<style>{_CSS}</style></head>
<body><main>
<h1>Requirements check: {e(p.name)}</h1>
<p class="sub">Generated by reqcheck on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC</p>
<div class="cards">{cards}</div>

<h2>Findings</h2>
<div class="filters">
  <label><input type="checkbox" value="error" checked> errors</label>
  <label><input type="checkbox" value="warning" checked> warnings</label>
  <label><input type="checkbox" value="info" checked> info</label>
</div>
<table id="findings"><thead><tr><th>Severity</th><th>ID</th><th>Rule</th><th>Message and requirement text</th></tr></thead>
<tbody>{findings_html}</tbody></table>

<h2>Traceability matrix</h2>
<table><thead><tr><th>ID</th><th>Type</th><th>Text</th><th>EARS pattern</th><th>Derived from</th><th>Derived requirements</th><th>Verified by</th></tr></thead>
<tbody>{''.join(trace_rows)}</tbody></table>

<h2>Test cases</h2>
<table><thead><tr><th>ID</th><th>Method</th><th>Description</th><th>Verifies</th></tr></thead>
<tbody>{tests_rows}</tbody></table>
</main><script>{_JS}</script></body></html>
"""
